import { describe, expect, it } from 'vitest'
import { dismissTutorial, getTutorialSteps, wasTutorialDismissed } from './tutorial'

describe('tutorial por cargo', () => {
  it('funcionário não recebe passos de gestão', () => {
    const text = getTutorialSteps('employee', false).map((step) => `${step.title} ${step.body}`).join(' ')
    expect(text).not.toContain('Auditoria')
    expect(text).not.toContain('Custo')
    expect(text).toContain('Seu papel como funcionário')
  })
  it('admin recebe modo suporte', () => {
    const text = getTutorialSteps(null, true).map((step) => `${step.title} ${step.body} ${step.bullets.join(' ')}`).join(' ')
    expect(text).toContain('suporte')
    expect(text).toContain('Proprietário')
    expect(text).toContain('Gerente')
    expect(text).toContain('Funcionário')
    expect(text).toContain('Caixa de suporte')
    expect(text).toContain('suspender ou reativar')
  })
  it('funcionalidades essenciais aparecem nos tópicos de gestão', () => {
    const text = getTutorialSteps('manager', false).map((step) => `${step.title} ${step.body} ${step.bullets.join(' ')}`).join(' ')
    expect(text).toContain('contagens físicas')
    expect(text).toContain('Vendas')
    expect(text).toContain('Lista de compras')
    expect(text).toContain('porções')
    expect(text).toContain('Encontrar furo')
    expect(text).toContain('modelo oficial')
    expect(text).toContain('perecíveis')
    expect(text).toContain('sino')
    expect(text).toContain('Seu papel como gestor')
    expect(text).toContain('Ciclo diário entre ambientes')
    expect(text).toContain('compras diretas')
    expect(text).toContain('Fornecedores')
    expect(text).toContain('Movimentação em lote')
    expect(text).toContain('Conta, privacidade e suporte')
    const steps = getTutorialSteps('manager', false)
    expect(steps.some((step) => step.route === '/movimentacoes')).toBe(true)
  })
  it('segue sem localStorage', () => {
    expect(() => dismissTutorial(null, 'employee')).not.toThrow()
    expect(wasTutorialDismissed(null, 'employee')).toBe(false)
  })
  it('funcionário conhece offline, compras e suporte sem receber gestão', () => {
    const steps = getTutorialSteps('employee', false)
    const text = steps.map((step) => `${step.title} ${step.body} ${step.bullets.join(' ')}`).join(' ')
    expect(text).toContain('Perdas e lotes por planilha exigem conexão')
    expect(text).toContain('Lista de compras e reposição')
    expect(text).toContain('Suporte privado')
    expect(text).not.toContain('Auditoria')
  })
})
